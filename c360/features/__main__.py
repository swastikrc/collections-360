"""Feature store command line.

    python -m c360.features build                 # every promise -> warehouse/features/features.duckdb
    python -m c360.features get PTP-0001234       # live lookup (same SQL), compared with the batch row
    python -m c360.features validate-text         # text patterns vs the 500 hand-labelled agent notes
    python -m c360.features describe              # the catalogue: every feature, group, source, meaning
"""
import argparse
import json
import sys
from pathlib import Path

import duckdb

from c360.features import store

# text feature -> (label column test on labels/agent_notes_labels_public_500.csv, what the label means)
TEXT_CHECKS = {
    "hedged": ("label_ptp_mentioned AND label_ptp_intent_strength < 0.6", "promise made with weak intent (labelled strength < 0.6)"),
    "firm": ("label_ptp_mentioned AND label_ptp_intent_strength >= 0.6", "promise made with strong intent (labelled strength >= 0.6)"),
    "payday": ("label_stated_delay_reason = 'payroll_timing'", "delay reason labelled payroll timing"),
    "hardship": ("label_hardship IN ('clear', 'possible')", "hardship labelled clear or possible"),
    "hardship_ask": ("label_next_step = 'hardship_plan_review'", "next step labelled hardship plan review"),
    "dispute": ("label_dispute", "dispute labelled"),
    "distress": ("label_sentiment IN ('distressed', 'hostile', 'frustrated')", "sentiment labelled distressed / hostile / frustrated"),
}


def validate_text(out_dir=None, log=print) -> list[dict]:
    """Run the text patterns (the SQL regexes from definitions.yaml) on the labelled notes and score them."""
    from c360.layer2 import config as l2config
    defs = store.definitions()
    labels = l2config.settings().data_root / "labels" / "agent_notes_labels_public_500.csv"
    con = duckdb.connect()
    con.execute(f"ATTACH '{store.serving_db()}' AS srv (READ_ONLY)")
    con.execute("CREATE TEMP TABLE lab AS SELECT * FROM read_csv_auto(?, header = true)", [str(labels)])
    con.execute("CREATE TEMP TABLE notes AS SELECT n.note_id, lower(coalesce(n.note_text, '')) AS txt FROM srv.l2.agent_notes n "
                "JOIN lab USING (note_id)")
    rows = []
    for name, (cond, meaning) in TEXT_CHECKS.items():
        pat = defs["text_patterns"][name]
        tp, fp, fn, tn = con.execute(f"""
            SELECT count(*) FILTER (WHERE hit AND lab), count(*) FILTER (WHERE hit AND NOT lab),
                   count(*) FILTER (WHERE NOT hit AND lab), count(*) FILTER (WHERE NOT hit AND NOT lab)
            FROM (SELECT regexp_matches(n.txt, ?) AS hit, coalesce({cond}, FALSE) AS lab FROM notes n JOIN lab USING (note_id))""",
                                     [pat]).fetchone()
        prec = tp / (tp + fp) if tp + fp else None
        rec = tp / (tp + fn) if tp + fn else None
        rows.append({"pattern": name, "label": meaning, "positives": tp + fn, "flagged": tp + fp, "precision": prec, "recall": rec,
                     "accuracy": (tp + tn) / (tp + fp + fn + tn)})
    n = con.execute("SELECT count(*) FROM notes").fetchone()[0]
    fmt = lambda x: "-" if x is None else f"{x:.0%}"
    lines = [f"# Text feature check (agent notes, {n} hand-labelled)", "",
             "Generated by `python -m c360.features validate-text`: the regexes from `c360/features/definitions.yaml`, run in "
             "DuckDB exactly as the feature SQL runs them, against `labels/agent_notes_labels_public_500.csv`.", "",
             "| Pattern | Compared with label | Labelled | Flagged | Precision | Recall | Accuracy |", "|---|---|---:|---:|---:|---:|---:|"]
    lines += [f"| {r['pattern']} | {r['label']} | {r['positives']} | {r['flagged']} | {fmt(r['precision'])} | {fmt(r['recall'])} | "
              f"{fmt(r['accuracy'])} |" for r in rows]
    out = Path(out_dir or (store.ROOT / "outputs" / "features"))
    out.mkdir(parents=True, exist_ok=True)
    (out / "text_feature_check.md").write_text("\n".join(lines) + "\n")
    log("\n".join(lines))
    return rows


def describe() -> str:
    defs = store.definitions()
    lines = [f"# Feature catalogue ({defs['version']})", "", "Generated from `c360/features/definitions.yaml` "
             "(`python -m c360.features describe`). Entity: one promise to pay, as of the end of the call in which it was made.", "",
             "| Feature | Group | Source | Used by model | Meaning |", "|---|---|---|---|---|"]
    for f in store.feature_specs(defs):
        lines.append(f"| `{f['name']}` | {f['group']} | {f['source']} | {'yes' if f.get('use_in_model', True) else 'no (safeguard only)'} "
                     f"| {f['description']} |")
    lines += ["", "Groups:", ""] + [f"- **{g['name']}** ({g['source']}): {g['description']}" for g in defs["groups"]]
    return "\n".join(lines) + "\n"


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(prog="python -m c360.features", description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = ap.add_subparsers(dest="cmd", required=True)
    sub.add_parser("build")
    g = sub.add_parser("get")
    g.add_argument("ptp_id")
    sub.add_parser("validate-text")
    sub.add_parser("describe")
    a = ap.parse_args(argv)
    if a.cmd == "build":
        store.build()
        out = store.ROOT / "docs" / "features"
        out.mkdir(parents=True, exist_ok=True)
        (out / "feature_catalogue.md").write_text(describe())
    elif a.cmd == "get":
        live = store.online(a.ptp_id).get(a.ptp_id)
        if live is None:
            print(f"no promise {a.ptp_id}")
            return 1
        batch = store.offline(a.ptp_id).get(a.ptp_id) if store.features_db().exists() else None
        print(json.dumps(live, default=str, indent=2))
        if batch is not None:
            diff = [k for k in store.feature_names() if live[k] != batch[k]]
            print(f"batch row: {'identical' if not diff else 'DIFFERS on ' + ', '.join(diff)}")
    elif a.cmd == "validate-text":
        validate_text()
    elif a.cmd == "describe":
        print(describe())
    return 0


if __name__ == "__main__":
    sys.exit(main())
